// Dialect and Sister-Language Fallback Maps:
// Ensures Sanskrit, Maithili, Konkani, Nepali, Bodo, Dogri, Kashmiri, Manipuri, Santhali, Sindhi, Odia, Assamese, Malayalam, Urdu
// gracefully resolve to authentic local scripts or sister languages
const SISTER_FALLBACKS: Record<string, string> = {
  sa: 'hi',   // Sanskrit -> Hindi
  mai: 'hi',  // Maithili -> Hindi
  doi: 'hi',  // Dogri -> Hindi
  sat: 'hi',  // Santhali -> Hindi
  ne: 'hi',   // Nepali -> Hindi
  kok: 'mr',  // Konkani -> Marathi
  brx: 'as',  // Bodo -> Assamese
  mni: 'bn',  // Manipuri -> Bengali
  ks: 'ur',   // Kashmiri -> Urdu
  sd: 'hi',   // Sindhi -> Hindi
  od: 'hi',   // Odia -> Hindi (falls back if phrase not found)
  as: 'bn',   // Assamese -> Bengali fallback
  ml: 'ta',   // Malayalam -> Tamil fallback
  ur: 'hi'    // Urdu -> Hindi fallback
};

export function getPhraseTranslation(englishPhrase: string, langCode: string): string {
  if (!englishPhrase || langCode === 'en') {
    return englishPhrase;
  }

  const trimmed = englishPhrase.trim();

  // 1. Direct dictionary match
  if (PHRASE_DICTIONARY[langCode] && PHRASE_DICTIONARY[langCode][trimmed]) {
    return PHRASE_DICTIONARY[langCode][trimmed];
  }

  // 2. Case-insensitive dictionary match
  if (PHRASE_DICTIONARY[langCode]) {
    const lower = trimmed.toLowerCase();
    for (const [key, val] of Object.entries(PHRASE_DICTIONARY[langCode])) {
      if (key.toLowerCase() === lower) {
        return val;
      }
    }
  }

  // 3. Sister language fallback
  const sisterLang = SISTER_FALLBACKS[langCode];
  if (sisterLang && PHRASE_DICTIONARY[sisterLang]) {
    if (PHRASE_DICTIONARY[sisterLang][trimmed]) {
      return PHRASE_DICTIONARY[sisterLang][trimmed];
    }
  }

  // 4. Universal Hindi fallback for Indic regional representation
  if (langCode !== 'hi' && PHRASE_DICTIONARY['hi'] && PHRASE_DICTIONARY['hi'][trimmed]) {
    return PHRASE_DICTIONARY['hi'][trimmed];
  }

  return englishPhrase;
}
